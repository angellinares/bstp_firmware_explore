"""Write site/patches.js: what the patch page needs to make each mod's update file.

    .venv/Scripts/python tools/gen_site.py

Compares Arturia's update file with out/bsp_2.0.1.6-MOD.led (tools/build_patch.py)
or, when the mod's "page" in patches/mods.json names a version, with that kept
release: a newer build stays off the page until it has run on a device. Frame by frame
it keeps only the bytes that differ: our code, our call targets,
the stamp and the checksums. Arturia's file is named by its SHA-256, so none of
its bytes are in the output. Nothing is written unless replaying the edits on
Arturia's file gives the built file exactly.

Run it after every build_patch.py; tests/test_site.py fails when it is stale.
"""
import ast
import hashlib
import json
import os
import sys

import led
from build_patch import REPO, mods, stamp

STOCK = os.path.join(REPO, "00_Resources", "BeatStepPro_Firmware_Update_2_0_1_6.led")
BUILT = os.path.join(REPO, "out", "bsp_2.0.1.6-%s.led")
OUT = os.path.join(REPO, "site", "patches.js")


def sha(data):
    return hashlib.sha256(data).hexdigest()


def offered(name, mod):
    """-> (the version the page offers, its .led): the newest build, or the kept release "page" names."""
    if mod["page"] is True:
        return mod["changes"][0][0], BUILT % name
    return mod["page"], os.path.join(REPO, "out", "releases", "bsp_2.0.1.6-%s-%s.led" % (name, mod["page"]))


def number(version):
    return tuple(int(part) for part in version.split("."))


def upto(entries, version, at):
    """-> the entries that apply to a version: entry[at], when there, is the version it came with."""
    return [entry[:at] if at else entry for entry in entries
            if len(entry) <= at or number(entry[at]) <= number(version)]


def scenarios(name):
    """-> what a test file checks, one sentence per test, read from the test names."""
    with open(os.path.join(REPO, "tests", name), encoding="utf-8") as f:
        tree = ast.parse(f.read())
    names = [node.name[5:].replace("_", " ") for node in tree.body
             if isinstance(node, ast.FunctionDef) and node.name.startswith("test_")]
    return [text[0].upper() + text[1:] for text in names]


def edits(stock, built):
    """-> [[offset in the stock file's bytes, bytes to drop, new bytes as hex], ...]."""
    found, at = [], 0
    for a, b in zip(stock, built, strict=True):
        old, new = a.pack(), b.pack()
        if len(old) != len(new):
            # A block Arturia only erases, sent as data: the whole frame is ours.
            assert a.fill and not b.fill, "frame at %#x changed size" % a.offset
            found.append([at, len(old), new.hex()])
        else:
            i = 0
            while i < len(old):
                j = i
                while j < len(old) and old[j] != new[j]:
                    j += 1
                if j > i:
                    found.append([at + i, j - i, new[i:j].hex()])
                i = j + 1
        at += len(old)
    return found


def replay(data, found):
    out, pos = bytearray(), 0
    for at, drop, new in found:
        out += data[pos:at] + bytes.fromhex(new)
        pos = at + drop
    return bytes(out + data[pos:])


def build():
    """-> the text of site/patches.js."""
    stock_frames = led.read_led(STOCK)
    stock = b"".join(f.pack() for f in stock_frames)
    data = {"firmware": "BeatStep Pro 2.0.1.6", "stock_sha256": sha(stock), "stamp_length": len(stamp("trig")),
            "mods": []}
    for name, mod in mods().items():
        if not mod["page"]:
            continue
        version, path = offered(name, mod)
        frames = led.read_led(path)
        built = b"".join(f.pack() for f in frames)
        found = edits(stock_frames, frames)
        if replay(stock, found) != built:
            sys.exit("%s: the edits do not rebuild the file; nothing written" % name)
        from_end = len(built) - built.rindex(stamp(name, version))
        if data.setdefault("stamp_from_end", from_end) != from_end:
            sys.exit("%s: the stamp is not where the other mods have it" % name)
        data["mods"].append({"id": name, "name": mod["name"], "version": version,
                             "hardware": mod["hardware"], "summary": mod["summary"],
                             "guide": upto(mod.get("guide", []), version, 2), "doc": mod.get("doc"),
                             "changes": upto(mod["changes"], version, 0),
                             "device": mod["device"], "unchecked": mod["unchecked"],
                             "emulator": [[group, scenarios(tests)] for group, tests in upto(mod["tests"], version, 2)],
                             "sha256": sha(built),
                             "file_sha256": sha(built.hex().upper().encode()), "edits": found})
    return ("// Generated by tools/gen_site.py -- do not edit by hand.\n"
            "const PATCHES = %s;\n"
            "if (typeof module !== \"undefined\") module.exports = PATCHES;\n" % json.dumps(data, indent=1))


def main():
    text = build()
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    for mod in json.loads(text[text.index("{"):text.rindex("}") + 1])["mods"]:
        print("%-5s %s  %d edits, %d new bytes" % (
            mod["id"], mod["version"], len(mod["edits"]), sum(len(e[2]) // 2 for e in mod["edits"])))


if __name__ == "__main__":
    main()
